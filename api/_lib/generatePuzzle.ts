const bonusTileTypes: BonusTile[] = ["dl", "dw", "tl", "tw"];
const PUZZLE_DATE_CLAIM_TTL_SECONDS = 3 * 24 * 60 * 60;

const generateBonusTiles = () => {
	// generate list of bonus tiles of random length
	const bonusTileCount = getRandomInt(4, 11);
	const bonuses = Array.from({ length: bonusTileCount }, () => {
		const index = getRandomInt(0, bonusTileTypes.length);
		return bonusTileTypes[index];
	});

	const cellsMap = structuredClone(boardTemplate.cellsById);

	const verticalCellCandidates = [...boardTemplate.verticalAxis].filter(c => c !== boardTemplate.centerCellId);
	const horizontalCellCandidates = [...boardTemplate.horizontalAxis].filter(c => c !== boardTemplate.centerCellId);
	let allCellCandidates = [...verticalCellCandidates, ...horizontalCellCandidates];

	let verticalBonuses = 0;
	let horizontalBonuses = 0;
	for (const bonus of bonuses) {
		const targetAxis =
			verticalBonuses < MIN_BONUSES_BY_AXIS ? "vertical" : horizontalBonuses < MIN_BONUSES_BY_AXIS ? "horizontal" : "both";
		let targetCandidates =
			targetAxis === "vertical" ? verticalCellCandidates : targetAxis === "horizontal" ? horizontalCellCandidates : allCellCandidates;
		if (targetCandidates.length === 0) targetCandidates = allCellCandidates;
		if (targetCandidates.length === 0) break;

		const index = getRandomInt(0, targetCandidates.length);
		const selectedCell = targetCandidates[index];
		const targetCell = cellsMap[selectedCell];

		if (targetCell) {
			targetCell.bonus = bonus;
			if (boardTemplate.verticalAxis.includes(targetCell.id)) verticalBonuses++;
			if (boardTemplate.horizontalAxis.includes(targetCell.id)) horizontalBonuses++;
		}

		targetCandidates.splice(index, 1);
		if (targetAxis !== "both") allCellCandidates = allCellCandidates.filter(el => el !== selectedCell);
	}

	return cellsMap;
};

const getLatestPuzzleIdFromList = async (): Promise<number> => {
	const puzzlesLen = await redis.llen("puzzles:all");
	if (!puzzlesLen) return 0;
	const allPuzzles = await redis.lrange("puzzles:all", 0, puzzlesLen);
	const allIds = allPuzzles.map(el => Number(el)).filter(id => Number.isInteger(id) && id > 0);
	return allIds.length ? Math.max(...allIds) : 0;
};

const getNextPuzzleId = async (): Promise<number> => {
	const existingCounter = await redis.get<number>("puzzles:next-id");

	if (typeof existingCounter !== "number" || !Number.isInteger(existingCounter) || existingCounter < 0) {
		const latestKnownId = await getLatestPuzzleIdFromList();
		await redis.set("puzzles:next-id", latestKnownId, { nx: true });
	}

	const id = await redis.incr("puzzles:next-id");
	if (!Number.isInteger(id) || id <= 0) {
		throw new Error(`Invalid puzzle id generated by counter: ${String(id)}`);
	}
	return id;
};

const rollbackPuzzleIdCounter = async (allocatedPuzzleId: number): Promise<void> => {
	if (!Number.isInteger(allocatedPuzzleId) || allocatedPuzzleId <= 0) return;
	const currentCounter = await redis.get<number>("puzzles:next-id");
	if (currentCounter === allocatedPuzzleId) {
		await redis.decr("puzzles:next-id");
	}
};

const getPuzzleDate = (): string => moment().tz("Pacific/Kiritimati").format("YYYY-MM-DD");

const tryClaimPuzzleDate = async (date: string, claimToken: string): Promise<boolean> => {
	const claimKey = `puzzle:date:${date}`;
	const claimResult = await redis.set(claimKey, claimToken, { nx: true, ex: PUZZLE_DATE_CLAIM_TTL_SECONDS });
	return claimResult === "OK";
};

const releasePuzzleDateClaim = async (date: string, claimToken: string): Promise<void> => {
	const claimKey = `puzzle:date:${date}`;
	const activeClaimToken = await redis.get<string>(claimKey);
	if (activeClaimToken === claimToken) {
		await redis.del(claimKey);
	}
};

export const generatePuzzleStructure = async ({ letters, claimToken }: { letters: string[7]; claimToken: string }) => {
	const letterArr = Array.from(letters);
	if (letterArr.length !== 7) {
		throw new Error(`Expected 7 letters for puzzle rack, received ${letterArr.length}: ${letters}`);
	}
	const date = getPuzzleDate();
	const id = await getNextPuzzleId();
	console.log(`Puzzle id: ${id}.\nPuzzle date: ${date}.`);
	const rackTiles = letterArr.map(letter => ({ id: randomUUID(), letter })) as unknown as RackTiles;
	const board = {
		...structuredClone(boardTemplate),
		cellsById: generateBonusTiles(),
	};
	const generation = {
		seed: `${id}-${date}-${letters}`,
		bonusDistributionVersion: "v2",
		scoringVersion: "v1",
		dictionaryVersion: "v1",
		dateClaimToken: claimToken,
	};

	return {
		id,
		date,
		rackTiles,
		rack: letters.toLocaleLowerCase(),
		generation,
		board,
	};
};

export const generatePuzzle = async () => {
	let claimedDate: string | null = null;
	let claimToken: string | null = null;
	let shouldKeepDateClaim = false;
	let allocatedPuzzleId: number | null = null;

	try {
		const { letters, dictionary } = await generateRackLetters();
		if (!letters || !dictionary?.length) return;
		console.log("Generated rack letters: ", letters.toUpperCase());
		console.log("Valid words found: ", dictionary.length);

		claimedDate = getPuzzleDate();
		claimToken = randomUUID();
		const didClaimDate = await tryClaimPuzzleDate(claimedDate, claimToken);
		if (!didClaimDate) {
			throw new Error(`Puzzle for date ${claimedDate} is already being generated or already exists.`);
		}

		const puzzle = await generatePuzzleStructure({ letters, claimToken });
		allocatedPuzzleId = puzzle.id;
		console.log("Puzzle config generated successfully.");
		const rackKey = `puzzle:${puzzle.id}`;
		const topScoringWords = calculateTopScoringWords(puzzle, dictionary, { limit: 20 });
		const puzzleEnvelope: PuzzleEnvelope = {
			id: puzzle.id,
			date: puzzle.date,
			puzzle,
			dictionary,
			createdAt: new Date(),
			topScoringWords,
		};
		console.log("Puzzle envelope created.");
		const pipeline = redis.pipeline();
		pipeline.lpush("puzzles:all", puzzle.id);
		pipeline.lpush("racks:all", letters);
		pipeline.set(rackKey, JSON.stringify(puzzleEnvelope), { ex: 3 * 60 * 60 * 24 });
		await pipeline.exec();
		shouldKeepDateClaim = true;
		console.log("Data uploaded.");
		return puzzleEnvelope;
	} catch (error) {
		console.error(error);
	} finally {
		if (!shouldKeepDateClaim && claimedDate && claimToken) {
			try {
				await releasePuzzleDateClaim(claimedDate, claimToken);
			} catch (claimReleaseError) {
				console.error("Failed to release puzzle date claim", claimReleaseError);
			}
		}
		if (!shouldKeepDateClaim && typeof allocatedPuzzleId === "number") {
			try {
				await rollbackPuzzleIdCounter(allocatedPuzzleId);
			} catch (counterRollbackError) {
				console.error("Failed to roll back puzzle id counter", counterRollbackError);
			}
		}
	}
};
